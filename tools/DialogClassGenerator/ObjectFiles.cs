using System.Linq;

namespace DialogClassGenerator
{
    /// <summary>The classes of the drawing object files (<see cref="ObjectFileSpecs"/>).</summary>
    internal static partial class Program
    {
        /// <summary>Namespace of the drawing object files and of their own pages.</summary>
        private const string ObjectNamespace = "TeklaHelper.DrawingAttribute.DrawingObjects";

        private static string WriteObjectFile(ObjectFileSpec file)
        {
            var w = new CodeWriter();
            w.Line("// <auto-generated>");
            w.Line("//     Generated by tools/DialogClassGenerator (ObjectFileSpecs.cs). Do not edit: change the generator or its input and");
            w.Line("//     run it again (see CLAUDE.md).");
            w.Line("// </auto-generated>");
            w.Line();
            w.Line("namespace " + ObjectNamespace);
            w.Open();
            string openApi = file.OpenApi != null
                ? $" The Open API reads it by name with {file.OpenApi} (checked in Tekla 2025)."
                : " No attribute class of the Open API reads it by name (checked in Tekla 2025): the dialog loads it.";
            w.Summary(file.Summary + openApi);
            w.Line($"public sealed partial class {file.Class} : global::TeklaHelper.DrawingAttribute.AttributeFile");
            w.Open();
            w.Summary("File extension.");
            w.Line($"public const string FileExtension = \"{file.Extension}\";");
            w.Line();
            w.Summary("Creates an empty file.");
            w.Line($"public {file.Class}()");
            w.Open();
            foreach ((string property, string page, string prefix, _) in file.Pages)
            {
                w.Line($"{property} = new {PageType(page)}(Values, {(prefix.Length == 0 ? "string.Empty" : $"\"{prefix}\"")});");
            }

            w.Close();
            w.Line();
            bool ownPages = file.Pages.All(page => IsOwnPage(PageSpecs.All.Single(s => s.Class == page.Page), file));
            string values = ownPages
                ? $"The values are the defaults of the page (<c>SetDefaults()</c>: the value most of the {file.Extension} files shipped with Tekla hold, else the dialog's default)."
                : $"The values are those most of the {file.Extension} files shipped with Tekla hold (at least three files){(file.Extension == ".rdim" ? ", else those of the .dim files" : string.Empty)}, else those of the file saved from the Tekla 2025 dialog; <c>SetDefaults()</c> of the page writes the defaults of the page's own file type instead.";
            w.Summary($"Creates a file with every key of a {file.Extension} file, so that Tekla takes nothing from the <c>standard</c> file of the environment. {values} The file uses code page 1252: set <see cref=\"global::TeklaHelper.DrawingAttribute.AttributeFile.CodePage\"/> before saving Japanese or Korean text.");
            w.Line($"public static {file.Class} CreateDefault()");
            w.Open();
            w.Line($"var file = new {file.Class}();");
            w.Line($"global::TeklaHelper.DrawingAttribute.FileDefaults.Apply(file.Values, global::TeklaHelper.DrawingAttribute.FileDefaults.{file.Table}.Table);");
            foreach ((string property, string page, _, _) in file.Pages.Where(p => IsOwnPage(PageSpecs.All.Single(s => s.Class == p.Page), file)))
            {
                w.Line($"file.{property}.SetDefaults();");
            }

            w.Line("return file;");
            w.Close();
            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line("public override string Extension => FileExtension;");
            foreach ((string property, string page, _, string summary) in file.Pages)
            {
                w.Line();
                w.Summary(summary);
                w.Line($"public {PageType(page)} {property} {{ get; }}");
            }

            if (file.MarksSummary != null)
            {
                w.Line();
                w.Summary(file.MarksSummary);
                w.Line("public global::System.Collections.Generic.IEnumerable<DimensionMark> Marks => new[]");
                w.Open();
                foreach ((string property, _, _, _) in file.Pages.Where(p => p.Page == "DimensionMark"))
                {
                    w.Line(property + ",");
                }

                w.Close(";");
            }

            if (file.DialogContent is (string read, string[] writes, string dialog, string note))
            {
                string keys = string.Join(", ", writes.Select(k => $"<c>{k}</c>"));
                w.Line();
                w.Summary($"What the marks show: the one content table of the {dialog} dialog of the drawing editor, which reads <c>{read}</c> and saves it into {keys}.{note} Checked in Tekla 2025: a file with a different text in each content key, loaded and saved again by the dialog. Setting it writes those keys the same way; null empties them. Each get returns a copy, to be assigned back after a change.");
                w.Line("public global::TeklaHelper.DrawingAttribute.Marks.MarkContent Elements");
                w.Open();
                w.Line($"get => Properties.GetMarkContentOrNull(\"{read}\");");
                w.Line("set");
                w.Open();
                foreach (string key in writes)
                {
                    w.Line($"Properties.SetMarkContent(\"{key}\", value);");
                }

                w.Close();
                w.Close();
            }

            w.Line();
            w.Line("/// <inheritdoc />");
            w.Line($"protected override string LegacyKeyPrefix => \"{file.LegacyKeyPrefix}\";");
            w.Close();
            w.Close();
            return w.ToString();
        }

        /// <summary>The type of a page for a file class in the namespace of the drawing objects.</summary>
        private static string PageType(string page)
        {
            PageSpec spec = PageSpecs.All.Single(s => s.Class == page);
            return spec.Namespace == ObjectNamespace ? page : $"global::{spec.Namespace}.{page}";
        }
    }
}
